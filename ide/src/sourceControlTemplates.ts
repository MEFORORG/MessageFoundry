// POSIX hook (Git for Windows runs it via bundled sh). Fails OPEN when Python / the package isn't
// available (a non-developer checkout shouldn't be blocked), fails CLOSED on a bad config (the
// `check` exit code propagates via exec). __CONFIG_DIR__/__MESSAGES_DIR__ are templated at setup.
// The project .venv is probed BEFORE the PATH lookup, so a workstation whose only interpreter is the
// project's own venv still runs the check rather than skipping it (BACKLOG #5414). `-P` keeps the
// commit's working directory off sys.path, as the engine's documented `serve` line does, so a
// `messagefoundry/` folder in the repository is never imported in place of the installed package.
// The IDE's own pre-flight goes through cli.ts `run()`, which passes `-P` too (BACKLOG #5409).
export const PRE_COMMIT_TEMPLATE = `#!/bin/sh
# MessageFoundry pre-commit checks — generated by the VS Code extension.
# Runs \`messagefoundry check\` so a commit can't introduce a broken config.
# Bypass once with: git commit --no-verify

# Prefer a project virtualenv if present (Windows + POSIX layouts); only then fall back to PATH.
if [ -x ".venv/Scripts/python.exe" ]; then
  PY=".venv/Scripts/python.exe"
elif [ -x ".venv/bin/python" ]; then
  PY=".venv/bin/python"
else
  PY=python
  command -v python >/dev/null 2>&1 || PY=python3
  if ! command -v "$PY" >/dev/null 2>&1; then
    echo "MessageFoundry: python not found; skipping checks." >&2
    exit 0
  fi
fi

if ! "$PY" -P -c "import messagefoundry" >/dev/null 2>&1; then
  echo "MessageFoundry: 'messagefoundry' not importable in this environment; skipping checks." >&2
  exit 0
fi

exec "$PY" -P -m messagefoundry check --config __CONFIG_DIR__ --messages __MESSAGES_DIR__
`;

/** The text setup shows and commits, which depends on whether it wrote the commit hook. */
export interface SetupText {
  readonly done: string;
  readonly hasHistory: string;
  readonly commitMessage: string;
  readonly commitFailed: string;
  readonly offerBaseline: string;
  readonly committedAnyway: string;
}

/**
 * What setup did with the commit hook: wrote none (`none`, a path setting names a folder outside the
 * workspace), wrote it but left core.hooksPath pointing elsewhere or unset (`written`), or wrote it
 * and pointed core.hooksPath at it (`wired`). Only `wired` turns on checks on commit.
 */
export type HookState = "none" | "written" | "wired";

/**
 * {@link SetupText} for a setup in the given {@link HookState}. Unless the hook is wired, setup must
 * not say checks run on commit, and without a hook it must not name a hook file it never wrote
 * (BACKLOG #5404).
 */
export function setupText(hook: HookState): SetupText {
  const files = hook !== "none" ? `.gitignore, .gitattributes and ${HOOK_REL}` : ".gitignore and .gitattributes";
  const hasHistory = `MessageFoundry: this repository already has commits, so no baseline commit was made. Review and commit ${files} yourself.`;
  if (hook === "wired") {
    return {
      done: "MessageFoundry: version control & checks are set up.",
      hasHistory,
      commitMessage: "Initial commit (MessageFoundry checks enabled)",
      commitFailed: "MessageFoundry: the commit hook reported an issue — see the 'MessageFoundry Checks' output.",
      offerBaseline:
        "A required check hasn't passed yet. You can still commit this as your baseline snapshot — the checks run on every commit after it, so you can fix the flagged items next. Details are in the 'MessageFoundry Checks' output.",
      committedAnyway:
        "MessageFoundry: baseline committed. Checks are active for your next commit — fix the flagged items in 'MessageFoundry Checks' before then.",
    };
  }
  const { done, what } =
    hook === "written"
      ? {
          done: `MessageFoundry: version control is set up and ${HOOK_REL} was written, but core.hooksPath does not point git at it, so this setup did not turn on checks on commit. The 'MessageFoundry Checks' output says why core.hooksPath was not set.`,
          what: "did not wire its commit hook",
        }
      : {
          done: "MessageFoundry: version control is set up, but this setup wrote no commit hook and did not set core.hooksPath, so it did not turn on checks on commit. Set the path settings to folders inside the workspace and run setup again to add it.",
          what: "set up no commit hook",
        };
  return {
    done,
    hasHistory,
    commitMessage: "Initial commit",
    commitFailed: "MessageFoundry: the commit failed — see the 'MessageFoundry Checks' output.",
    offerBaseline:
      `A required check hasn't passed yet. You can still commit this as your baseline snapshot. This setup ${what}, so it did not turn on checks for later commits; run the checks yourself after fixing the flagged items. Details are in the 'MessageFoundry Checks' output.`,
    committedAnyway:
      `MessageFoundry: baseline committed. This setup ${what}, so it did not turn on checks for later commits — fix the flagged items in 'MessageFoundry Checks'.`,
  };
}
