// POSIX hook (Git for Windows runs it via bundled sh). Fails OPEN when Python / the package isn't
// available (a non-developer checkout shouldn't be blocked), fails CLOSED on a bad config (the
// `check` exit code propagates via exec). __CONFIG_DIR__/__MESSAGES_DIR__ are templated at setup.
// The project .venv is probed BEFORE the PATH lookup, so a workstation whose only interpreter is the
// project's own venv still runs the check rather than skipping it (BACKLOG #5414). `-P` keeps the
// commit's working directory off sys.path, as the engine's documented `serve` line does, so a
// `messagefoundry/` folder in the repository is never imported in place of the installed package.
// The IDE's own pre-flight goes through cli.ts `run()`, which does not pass `-P` yet.
export const PRE_COMMIT_TEMPLATE = `#!/bin/sh
# MessageFoundry pre-commit checks — generated by the VS Code extension.
# Runs \`messagefoundry check\` so a commit can't introduce a broken config.
# Bypass once with: git commit --no-verify

# Prefer a project virtualenv if present (Windows + POSIX layouts); only then fall back to PATH.
if [ -x ".venv/Scripts/python.exe" ]; then
  PY=".venv/Scripts/python.exe"
elif [ -x ".venv/bin/python" ]; then
  PY=".venv/bin/python"
else
  PY=python
  command -v python >/dev/null 2>&1 || PY=python3
  if ! command -v "$PY" >/dev/null 2>&1; then
    echo "MessageFoundry: python not found; skipping checks." >&2
    exit 0
  fi
fi

if ! "$PY" -P -c "import messagefoundry" >/dev/null 2>&1; then
  echo "MessageFoundry: 'messagefoundry' not importable in this environment; skipping checks." >&2
  exit 0
fi

exec "$PY" -P -m messagefoundry check --config __CONFIG_DIR__ --messages __MESSAGES_DIR__
`;
