"""Write one sweep step's connection-scale graph into a generated config directory (BACKLOG #3132).

WHY THIS EXISTS. ``harness/config/connscale/graph.py`` reads its shape from ``MEFOR_CONNSCALE_*``.
That works for the engine process, which the runner hands those variables. It does not work for a
``[sandbox].mode = "subprocess"`` worker: the worker runs the config again under an allowlisted
environment (``messagefoundry/childenv.py``), and ``[sandbox].pass_environment`` refuses every
``MEFOR_`` name, by design, so the engine's secrets stay out of the worker. A worker on the env route
therefore builds the default 50-connection, ``cheap`` graph whatever the step asked for. The count
and the name prefix change connection names, so the engine's shape check refuses that worker. The
transform changes no name, so a worker would pass that check and quietly run ``cheap`` while the
engine was told ``edit``.

So the runner writes the step's shape into the config module itself, as literals, and serves that
directory. The engine and every worker then run the same bytes: a worker loads the snapshot of the
directory its engine loaded, so nothing about the shape depends on an environment variable. Neither
``childenv.py`` nor ``pass_environment`` is widened to get there.

``harness/config/connscale/gen_toml.py`` (the reload-latency directory) is the precedent for a
generated config directory. The wiring itself stays in one place,
:func:`harness.config.connscale._wire.wire_graph`, and the shape is validated by
:func:`harness.config.connscale._shape.make_connscale_shape` here, before anything is written, and
again when the module runs. Every value is synthetic and generic.
"""

from __future__ import annotations

import dataclasses
from pathlib import Path

from harness.config.connscale._shape import ConnScaleShape, make_connscale_shape

#: The generated config module's file name. Not ``_``-prefixed, so the loader loads it.
GRAPH_MODULE = "connscale_graph.py"
#: The prefix of the temp directory the runner generates per step. An engine serving one carries it
#: on its command line, which is how the smoke's leak census finds a sweep engine.
STEP_CONFIG_DIR_PREFIX = "mefor-connscale-cfg-"

_TEMPLATE = '''# SPDX-License-Identifier: AGPL-3.0-or-later
# Copyright (C) 2026 MessageFoundry Foundation, LLC and contributors
"""Generated by harness/load/connscale/stepconfig.py for one connscale sweep step (BACKLOG #3132).

The shape is written here as literals rather than read from the environment, so a sandbox worker
builds the same graph as its engine. Synthetic and generic; do not edit.
"""

from harness.config.connscale._shape import make_connscale_shape
from harness.config.connscale._wire import wire_graph

wire_graph(
    make_connscale_shape(
{arguments}    )
)
'''


def graph_module_text(shape: ConnScaleShape) -> str:
    """The generated config module for ``shape``. Every field of :class:`ConnScaleShape` is written,
    read from the dataclass rather than listed here, so a field added later cannot be dropped and
    leave the worker on its default. Each value goes through ``repr`` of an ``int`` or a ``str``, so
    it is a Python literal whatever the string holds; the module re-validates it when it runs."""
    # Re-validated here so a shape built by hand, around make_connscale_shape, fails at generation
    # rather than inside the engine's startup. The keyword names are the field names, which a test
    # pins against make_connscale_shape's signature.
    checked = make_connscale_shape(**dataclasses.asdict(shape))
    arguments = "".join(
        f"        {name}={value!r},\n" for name, value in dataclasses.asdict(checked).items()
    )
    return _TEMPLATE.format(arguments=arguments)


def write_step_config_dir(config_dir: str | Path, shape: ConnScaleShape) -> Path:
    """Write the step's config directory at ``config_dir`` (created if absent) and return it. The
    directory holds exactly one config module, :data:`GRAPH_MODULE`."""
    path = Path(config_dir)
    path.mkdir(parents=True, exist_ok=True)
    module = path / GRAPH_MODULE
    module.write_text(graph_module_text(shape), encoding="utf-8")
    # Owner-only on POSIX whatever the umask, so the engine's config-source trust check, which
    # refuses a group- or world-writable config path, never refuses a step for the umask it ran
    # under. On Windows this only clears the read-only flag, and the access list decides.
    path.chmod(0o700)
    module.chmod(0o600)
    return path
