"""The packaged dependency auditor must see every pin, whatever its environment marker.

``messagefoundry/security/audit_all_platforms.py`` carries the defect, the measurement and the
reasoning. It ships in the wheel, so the engine's own gate (through the
``scripts/security/audit_all_platforms.py`` wrapper) and an adopter's generated ``audit-pin`` job run
one implementation. These tests drive it through an injected runner (no network, no pip, no
pip-audit). ``tests/test_audit_all_platforms.py`` pins the engine's workflows to it and
``tests/test_scaffold.py`` pins the adopter's.
"""

from __future__ import annotations

import subprocess
import sys
from collections.abc import Callable
from pathlib import Path

import pytest

from messagefoundry.security.audit_all_platforms import main, strip_markers
from tests._workflow_contexts import ROOT

LOCK = """\
# This file was autogenerated by uv via the following command:
#    uv export --all-extras --no-emit-project --format requirements.txt -o requirements.lock
colorama==0.4.6 ; sys_platform == 'win32' \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via pytest
idna==3.20 \\
    --hash=sha256:cccc
uvloop==0.23.0 ; platform_python_implementation != 'PyPy' and sys_platform != 'win32' \\
    --hash=sha256:dddd
"""

STRIPPED = """\
# This file was autogenerated by uv via the following command:
#    uv export --all-extras --no-emit-project --format requirements.txt -o requirements.lock
colorama==0.4.6 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via pytest
idna==3.20 \\
    --hash=sha256:cccc
uvloop==0.23.0 \\
    --hash=sha256:dddd
"""


def _recorder(status: int) -> tuple[list[list[str]], Callable[[list[str]], int]]:
    """A runner that records each command and answers ``status``, with the list it records into."""
    ran: list[list[str]] = []

    def run(cmd: list[str]) -> int:
        ran.append(cmd)
        return status

    return ran, run


def test_markers_are_removed_and_everything_else_kept() -> None:
    assert strip_markers(LOCK) == (
        STRIPPED,
        [
            "colorama==0.4.6 ; sys_platform == 'win32'",
            "uvloop==0.23.0 ; platform_python_implementation != 'PyPy' and sys_platform != 'win32'",
        ],
        3,
    )


def test_a_last_line_without_continuation_or_newline() -> None:
    assert strip_markers("sspilib==0.6.0 ; sys_platform == 'win32'")[0] == "sspilib==0.6.0"


def test_crlf_line_endings_are_kept() -> None:
    text = strip_markers("colorama==0.4.6 ; os_name == 'nt' \\\r\n    --hash=sha256:aa\r\n")[0]
    assert text == "colorama==0.4.6 \\\r\n    --hash=sha256:aa\r\n"


def test_an_empty_lock_is_refused_without_running_the_audit(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    src = tmp_path / "empty.lock"
    src.write_text("# only a header\n", encoding="utf-8")
    ran, run = _recorder(0)
    assert main([str(src)], run=run) == 2
    assert not ran
    assert "no requirement lines" in capsys.readouterr().err


def test_the_committed_lock_is_install_checked_then_the_stripped_copy_audited(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    src = tmp_path / "x.lock"
    src.write_text(LOCK, encoding="utf-8")
    seen: list[tuple[list[str], str]] = []

    def run(cmd: list[str]) -> int:
        seen.append((cmd, Path(cmd[cmd.index("-r") + 1]).read_text(encoding="utf-8")))
        return 0 if len(seen) == 1 else 1

    # The audit's status is the script's status, so a finding still reds the step.
    assert main([str(src), "--ignore-vuln", "PYSEC-0"], run=run) == 1
    [(check, checked), (audit, audited)] = seen
    # 1. The hash-checked dry-run install the old pip-audit path did, on the lock AS COMMITTED.
    assert check[1:5] == ["-P", "-m", "pip", "install"]
    assert {"--dry-run", "--ignore-installed", "--require-hashes"} <= set(check)
    assert checked == LOCK
    # 2. The audit, on the marker-free copy, with pip out of the loop and skips refused.
    assert audit[1:4] == ["-P", "-m", "pip_audit"]
    assert {"--disable-pip", "--strict"} <= set(audit)
    assert audit[-2:] == ["--ignore-vuln", "PYSEC-0"]
    assert audited == STRIPPED
    out = capsys.readouterr().out
    assert "3 pinned requirements, 2 un-gated" in out
    assert "colorama==0.4.6 ; sys_platform == 'win32'" in out


@pytest.mark.parametrize(
    "line", ["-r base.lock", "-e ./pkg", "--index-url https://example.invalid"]
)
def test_a_pip_option_line_is_refused(line: str, tmp_path: Path) -> None:
    src = tmp_path / "x.lock"
    src.write_text(f"{LOCK}{line}\n", encoding="utf-8")
    ran, run = _recorder(0)
    assert main([str(src)], run=run) == 2
    assert not ran


def test_a_failed_install_check_stops_before_the_audit(tmp_path: Path) -> None:
    src = tmp_path / "x.lock"
    src.write_text(LOCK, encoding="utf-8")
    ran, run = _recorder(1)
    assert main([str(src)], run=run) == 1
    assert len(ran) == 1


def test_the_module_needs_nothing_outside_the_standard_library() -> None:
    """The engine's gate imports it from a checkout with only the scanner lock installed.

    So importing it must not pull any third-party package, which the lazy package root allows.
    """
    probe = "import sys; sys.path.insert(0, sys.argv[1]); import messagefoundry.security.audit_all_platforms"
    # -S: no site-packages, so any third-party import fails here rather than passing on this venv.
    proc = subprocess.run(
        [sys.executable, "-S", "-P", "-c", probe, str(ROOT)],
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    assert proc.returncode == 0, proc.stderr
