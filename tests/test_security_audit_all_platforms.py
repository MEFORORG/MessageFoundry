_ENV_PROBE = (
    "import os, sys; "
    "sys.exit(3 if 'MEFOR_TEST_AUDIT_SECRET' in os.environ "
    "else 4 if os.environ.get('PIP_TEST_AUDIT_SETTING') != 'kept' else 0)"
)


def test_an_engine_secret_does_not_reach_pip_or_pip_audit(monkeypatch: pytest.MonkeyPatch) -> None:
    """The real runner hands its children childenv.non_engine_environment, not the whole environment.

    The control, a pip-style setting, must still arrive: pip reads its index and proxy from there.
    """
    monkeypatch.setenv("MEFOR_TEST_AUDIT_SECRET", "marker-not-a-secret")
    monkeypatch.setenv("PIP_TEST_AUDIT_SETTING", "kept")
    assert _run([sys.executable, "-c", _ENV_PROBE]) == 0


def test_a_relative_pythonpath_entry_does_not_reach_pip_or_pip_audit(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """A relative entry would put the working directory back on a ``-P`` child's ``sys.path``."""
    monkeypatch.setenv("PYTHONPATH", os.pathsep.join([".", str(tmp_path)]))
    probe = f"import os, sys; sys.exit(os.environ.get('PYTHONPATH') != {str(tmp_path)!r})"
    assert _run([sys.executable, "-c", probe]) == 0


def test_the_module_needs_nothing_outside_the_standard_library() -> None:
    """The engine's gate imports it from a checkout with only the scanner lock installed.

    So importing it must not pull any third-party package, which the lazy package root allows.
    """
    probe = "import sys; sys.path.insert(0, sys.argv[1]); import messagefoundry.security.audit_all_platforms"
    # -S: no site-packages, so any third-party import fails here rather than passing on this venv.
    proc = subprocess.run(
        [sys.executable, "-S", "-P", "-c", probe, str(ROOT)],
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    assert proc.returncode == 0, proc.stderr
